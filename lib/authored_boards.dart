List<int> _neighbors(int index) => [
  if (index >= 9) index - 9,
  if (index % 9 < 8) index + 1,
  if (index < 72) index + 9,
  if (index % 9 > 0) index - 1,
];

List<VariantRule> _knightRules() => [
  for (var first = 0; first < 81; first++)
    for (var second = first + 1; second < 81; second++)
      if (((first ~/ 9 - second ~/ 9).abs() == 1 &&
              (first % 9 - second % 9).abs() == 2) ||
          ((first ~/ 9 - second ~/ 9).abs() == 2 &&
              (first % 9 - second % 9).abs() == 1))
        VariantRule(RuleKind.antiKnight, [first, second]),
];
